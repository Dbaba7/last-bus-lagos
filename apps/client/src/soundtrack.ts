import type { SoundMood } from '@lastbus/shared';
/**
 * Licensed music, kept apart from the voices and the synthesized effects. A track only plays from a file when its rights are
 * signed (`licensed`), the file is really in `src/music/` and the player has Licensed music on; anything else silently plays
 * the generated placeholder through the same path, so swapping a real file in changes nothing in a scene. The folder is in
 * .gitignore: nothing goes in it until a licence does. `src` is the file name without its extension, `cueIn` and `cueOut` the
 * excerpt in seconds, `placeholder` the generated track that stands in (itself, for a generated track), and `unlock` the
 * mission that opens it on a future Soundtrack page.
 */
export interface Track { id: string; title: string; artist: string; credit: string; src?: string; placeholder: string; licensed: boolean; cueIn: number; cueOut: number; unlock: string }
export const TRACKS: Track[] = [
  { id: 'danfo-groove', title: 'Danfo Groove', artist: 'Last Bus: Lagos', credit: 'Original placeholder, generated by the game', placeholder: 'danfo-groove', licensed: true, cueIn: 0, cueOut: 90, unlock: 'the-passenger' },
  // The song on Danfo 247's radio. No file and no licence yet; see Milestone 7 in the handoff.
  { id: 'radio-song', title: 'Radio song', artist: '', credit: '', placeholder: 'danfo-groove', licensed: false, cueIn: 0, cueOut: 60, unlock: 'the-passenger' }
];
const found = import.meta.glob('./music/*.{mp3,m4a,ogg}', { query: '?url', import: 'default', eager: true }) as Record<string, string>;
const FILES = Object.fromEntries(Object.entries(found).map(([path, url]) => [path.slice(8).replace(/\.[^.]+$/, ''), url]));
/** The track to play for a station, and its file if it has one. No `url` means the generated placeholder. Talk stations have no track. */
export function trackFor(id: string, allowed: boolean, files: Record<string, string> = FILES, tracks = TRACKS) {
  const track = tracks.find(t => t.id === id); if (!track) return undefined;
  const url = track.licensed && allowed && track.src ? files[track.src] : undefined;
  return url ? { track, url } : { track: tracks.find(t => t.id === track.placeholder) ?? track, url: undefined };
}
/** The street's sound while the story says this. `shelter` is a story on the shelter map. */
export function moodFor(flags: { has(flag: string): boolean }, shelter: boolean): SoundMood {
  return shelter ? 'shelter' : flags.has('blackout') ? 'dusk' : flags.has('live') ? 'live' : flags.has('city') ? 'restored' : 'dusk';
}
// About 107 BPM, so a bar is a whole number of samples: twenty bars, played twice, make exactly the ninety seconds.
const RATE = 16000, BEAT = 9000, BARS = 20;
/** A seeded generator, so the placeholder is the same original piece on every device. */
const seeded = (seed: number) => () => (seed = seed * 16807 % 2147483647) / 2147483647;
/** One bar of the placeholder's pattern, added into `mix`. It wraps around the end, so ringing notes carry over the loop point. */
function renderBar(mix: Float32Array, bar: number) {
  const size = mix.length, start = bar * 4 * BEAT, step16 = BEAT / 4, rand = seeded(9173 + bar * 311);
  const add = (at: number, length: number, sample: (i: number, t: number) => number) => { const from = Math.round(at); for (let i = 0; i < length; i++) mix[(from + i) % size] += sample(i, i / RATE); };
  const kick = (at: number, v: number) => add(at, 0.2 * RATE, (_, t) => Math.sin(2 * Math.PI * (50 * t + 2.8 * (1 - Math.exp(-t * 28)))) * Math.exp(-t * 20) * v);
  const skin = (at: number, pitch: number, v: number) => add(at, 0.14 * RATE, (_, t) => Math.sin(2 * Math.PI * pitch * t * (1 - t * 0.9)) * Math.exp(-t * 26) * v);
  const shaker = (at: number, v: number) => { let last = 0; add(at, 0.035 * RATE, (_, t) => { const n = rand() * 2 - 1, high = n - last; last = n; return high * Math.exp(-t * 110) * v; }); };
  const bell = (at: number, v: number) => add(at, 0.09 * RATE, (_, t) => (Math.sin(2 * Math.PI * 1720 * t) + Math.sin(2 * Math.PI * 2510 * t) * 0.6) * Math.exp(-t * 55) * v);
  const bass = (at: number, hz: number, seconds: number, v: number) => add(at, seconds * RATE, (i, t) => (Math.sin(2 * Math.PI * hz * t) + Math.sin(4 * Math.PI * hz * t) * 0.35 + Math.sin(6 * Math.PI * hz * t) * 0.14) * Math.min(1, i / 60) * Math.exp(-t * 3.4) * v);
  // Guitar: a plucked string (Karplus-Strong), which costs almost nothing and sounds like a string down a small speaker.
  const pluck = (at: number, hz: number, seconds: number, v: number) => {
    const period = Math.max(2, Math.round(RATE / hz)), line = new Float32Array(period); for (let i = 0; i < period; i++) line[i] = rand() * 2 - 1;
    let p = 0; add(at, seconds * RATE, () => { const next = (p + 1) % period, out = line[p]; line[p] = (out + line[next]) * 0.496; p = next; return out * v; });
  };
  // A plain highlife-style turnaround in G. The guitar answers itself every four bars and thins out for the last eight bars.
  const root = [98, 130.8, 146.8, 130.8][bar % 4], third = root * 1.26, fifth = root * 1.5, middle = bar >= 12;
  for (const [step, v] of [[0, 0.5], [6, 0.32], [8, 0.46], [11, 0.26]] as const) kick(start + step * step16, v);
  for (let step = 0; step < 16; step++) shaker(start + step * step16, step % 2 ? 0.08 : 0.14);
  for (const step of [0, 3, 6, 10, 12]) bell(start + step * step16, 0.1);
  for (const [step, pitch, v] of [[4, 196, 0.26], [7, 220, 0.2], [12, 196, 0.26], [14, 165, 0.22], [15, 150, 0.24]] as const) if (middle || step !== 7) skin(start + step * step16, pitch, v);
  for (const [step, hz, seconds] of [[0, root, 0.5], [3, root, 0.25], [6, fifth, 0.3], [8, root, 0.45], [11, third, 0.25], [14, fifth, 0.25]] as const) bass(start + step * step16, hz, seconds, 0.3);
  const lick = middle ? [0, 3, 6, 8, 11, 14] : [0, 2, 3, 5, 6, 8, 10, 11, 13, 14], notes = [root * 4, third * 4, fifth * 4, root * 8, fifth * 4, third * 4];
  lick.forEach((step, i) => pluck(start + step * step16, notes[(i + (bar % 4 === 3 ? 2 : 0)) % notes.length], 0.34, 0.16));
  if (bar % 8 === 7) for (const step of [12, 13, 14, 15]) skin(start + step * step16, 210 - step * 3, 0.24);
}
const patternLength = BARS * 4 * BEAT;
/** How long the placeholder is, in samples: the pattern twice, so it loops on the beat. */
export const placeholderLength = () => patternLength * 2;
/** Keeps the level sensible and turns the mix into 16-bit samples. */
function master(mix: Float32Array) { const pcm = new Int16Array(placeholderLength()); for (let i = 0; i < pcm.length; i++) pcm[i] = Math.tanh(mix[i % mix.length] * 1.5) * 26000; return pcm; }
/** The whole placeholder at once, for tests. */
export function renderPlaceholder() { const mix = new Float32Array(patternLength); for (let bar = 0; bar < BARS; bar++) renderBar(mix, bar); return master(mix); }
/** A standard WAV file around the samples, which every browser's audio element can play and seek. */
export function wavFile(pcm: Int16Array, rate = RATE) {
  const head = new DataView(new ArrayBuffer(44)), text = (at: number, s: string) => { for (let i = 0; i < s.length; i++) head.setUint8(at + i, s.charCodeAt(i)); };
  text(0, 'RIFF'); head.setUint32(4, 36 + pcm.byteLength, true); text(8, 'WAVEfmt '); head.setUint32(16, 16, true); head.setUint16(20, 1, true); head.setUint16(22, 1, true);
  head.setUint32(24, rate, true); head.setUint32(28, rate * 2, true); head.setUint16(32, 2, true); head.setUint16(34, 16, true); text(36, 'data'); head.setUint32(40, pcm.byteLength, true);
  return new Blob([head.buffer as ArrayBuffer, pcm.buffer as ArrayBuffer], { type: 'audio/wav' });
}
let generated: Promise<string> | undefined;
/** Renders the placeholder a bar at a time so a phone never stalls for it, once, and only when something is going to play it. */
export function placeholderUrl() {
  return generated ??= (async () => {
    const mix = new Float32Array(patternLength);
    for (let bar = 0; bar < BARS; bar++) { renderBar(mix, bar); await new Promise(resolve => setTimeout(resolve)); }
    return URL.createObjectURL(wavFile(master(mix)));
  })();
}
export interface RadioState { on: boolean; station: string; level: number; signal: number; muffled: boolean }
/** A radio cue from a scene; see CineCue. */
export interface RadioCue { radio: 'play' | 'stop'; station?: string; level?: number; signal?: number; muffled?: boolean; seconds?: number }
/** What the radio needs from the sound engine. `tape` plays a url from its cue-in, or stops with no url; `failed` means that url would not play. */
export interface RadioOutput {
  radioOn(): void; radioOff(click: boolean): void; radioSet(state: RadioState, seconds: number): void; radioBlip(): void;
  tape(url: string | undefined, cueIn: number, cueOut: number, failed: () => void): void;
}
const SILENT: RadioState = { on: false, station: '', level: 1, signal: 1, muffled: false };
/**
 * The bus radio as state. Cues only change what the radio should be doing, and `flush` (every frame) makes it so: skipping
 * applies a whole scene's cues in one go, so only where they ended up is ever played, and a song that scene started and
 * stopped never touches the network. Asking for the station already on leaves it playing where it is.
 */
export class Radio {
  state: RadioState = { ...SILENT };
  private shown: RadioState = { ...SILENT }; private seconds = 0; private blip = false; private tuned = ''; private ticket = 0; private licensed = true; private broken = false;
  constructor(private out: RadioOutput, private generate: () => Promise<string> = placeholderUrl) {}
  cue(cue: RadioCue, skipping = false) {
    const s = this.state, station = cue.radio === 'stop' ? '' : cue.station ?? s.station; this.seconds = skipping ? 0 : cue.seconds ?? 0.2;
    if (cue.radio === 'stop') { this.state = { ...SILENT }; return; }
    if (s.on && station !== s.station && !skipping) this.blip = true;
    s.on = true; s.station = station; s.level = cue.level ?? s.level; s.signal = cue.signal ?? s.signal; s.muffled = cue.muffled ?? s.muffled;
  }
  /** Silent at once with nothing left to come back: leaving a mission or starting a session. */
  off() { this.state = { ...SILENT }; this.seconds = 0; this.flush(); }
  /** The Licensed music setting; a song on the air swaps on the next frame. */
  allow(on: boolean) { if (on === this.licensed) return; this.licensed = on; this.broken = false; if (this.tuned) this.tuned = '?'; }
  flush() {
    const s = this.state, was = this.shown;
    if (s.on && !was.on) this.out.radioOn();
    if (!s.on && was.on) this.out.radioOff(this.seconds > 0);
    if (s.on && (!was.on || s.level !== was.level || s.signal !== was.signal || s.muffled !== was.muffled)) this.out.radioSet({ ...s }, this.seconds);
    if (this.blip && s.on) this.out.radioBlip(); this.blip = false; this.shown = { ...s }; this.tune();
  }
  /** The one place a song starts or stops. */
  private tune() {
    const pick = this.state.on ? trackFor(this.state.station, this.licensed && !this.broken) : undefined, key = pick ? pick.url ?? pick.track.id : '';
    if (key === this.tuned) return; this.tuned = key; const ticket = ++this.ticket;
    if (!pick) { this.out.tape(undefined, 0, 0, () => {}); return; }
    // A file that will not play falls back, silently, to the placeholder.
    const { track, url } = pick, failed = () => { if (ticket === this.ticket) { this.broken = true; this.tuned = '?'; } };
    if (url) this.out.tape(url, track.cueIn, track.cueOut, failed);
    else void this.generate().then(made => { if (ticket === this.ticket) this.out.tape(made, track.cueIn, track.cueOut, () => {}); });
  }
}
