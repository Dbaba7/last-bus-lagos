import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const url = process.env.GAME_URL || 'http://localhost:5173';
await mkdir('artifacts', { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || undefined, args: ['--enable-unsafe-swiftshader'] });
const errors = [], results = [];
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await context.newPage();
page.on('pageerror', e => errors.push(e.message));
page.on('console', e => { if (e.type() === 'error') errors.push(e.text()); });
try {
  await page.goto(url); await page.locator('#nav-story').waitFor();
  await page.waitForFunction(() => typeof window.lastBusDiagnostics === 'function' && window.lastBusDiagnostics().ready);
  await page.locator('#loading').waitFor({ state: 'hidden' });
  await page.screenshot({ path: 'artifacts/menu.png' }); results.push('menu rendered');
  await page.locator('#nav-training').click(); await page.locator('#practice').click();
  await page.waitForFunction(() => window.lastBusDiagnostics().mode === 'practice');
  if (await page.locator('#resume').isVisible()) await page.locator('#resume').click();
  await page.waitForFunction(() => document.pointerLockElement !== null);
  const initialAmmo = await page.locator('#ammo').innerText();
  await page.mouse.down(); await page.waitForTimeout(450); await page.mouse.up();
  await page.waitForFunction(start => Number(document.querySelector('#ammo').textContent) < Number(start), initialAmmo);
  await page.keyboard.press('r'); await page.waitForTimeout(2100);
  assert.equal(await page.locator('#ammo').innerText(), '30');
  await page.keyboard.press('2'); await page.waitForTimeout(350);
  await page.mouse.down(); await page.waitForTimeout(600); await page.mouse.up();
  assert.equal(await page.locator('#ammo').innerText(), '11');
  await page.keyboard.down('w'); await page.waitForTimeout(900); await page.keyboard.up('w');
  await page.screenshot({ path: 'artifacts/practice.png' });
  results.push('practice: pointer lock, fire, reload, semi-auto sidearm, keyboard movement');
  await page.keyboard.press('Escape');
  // Headless Chromium may retain lock for synthetic Escape; use the public browser API to release it.
  await page.evaluate(() => document.exitPointerLock());
  await page.locator('#pause-settings').click();
  await page.locator('[data-tab=Video]').click(); await page.locator('#quality').selectOption('low');
  await page.locator('#settings-close').click(); await page.locator('#leave-game').click();
  await page.locator('#screen-training [data-back]').click(); await page.locator('#nav-multiplayer').click(); await page.locator('#play').click(); await page.waitForFunction(() => window.lastBusDiagnostics().connected && window.lastBusDiagnostics().phase === 'WAITING');
  const second = await browser.newContext({ viewport: { width: 1280, height: 800 } });
  const friend = await second.newPage(); friend.on('pageerror', e => errors.push(e.message)); friend.on('console', e => { if (e.type() === 'error') errors.push(e.text()); });
  await friend.goto(url); await friend.locator('#loading').waitFor({ state: 'hidden' });
  await friend.locator('#nav-multiplayer').click(); await friend.locator('#play').click();
  await friend.waitForFunction(() => window.lastBusDiagnostics().connected && window.lastBusDiagnostics().players === 2);
  await page.waitForFunction(() => window.lastBusDiagnostics().players === 2);
  await friend.locator('#leave-lobby').click(); await page.locator('#leave-lobby').click();
  results.push('two independent browsers use public Play, share a real waiting room and return to the menu');
  await page.locator('#create').click();
  await page.waitForFunction(() => document.querySelector('#invite-link').value.length > 0, null, { timeout: 18000 });
  const invite = await page.locator('#invite-link').inputValue();
  await friend.goto(invite); await friend.locator('#nickname').fill('Second Passenger');
  await friend.locator('#join-form button[type=submit]').click();
  await page.waitForFunction(() => window.lastBusDiagnostics().players === 2, null, { timeout: 15000 });
  await page.locator('#start-match').click();
  await page.waitForFunction(() => window.lastBusDiagnostics().phase === 'ACTIVE', null, { timeout: 12000 });
  await friend.waitForFunction(() => window.lastBusDiagnostics().phase === 'ACTIVE');
  await page.screenshot({ path: 'artifacts/multiplayer.png' });
  results.push('two independent browser contexts joined an invitation and started an authoritative match');
  await page.locator('#resume').click(); await page.waitForFunction(() => document.pointerLockElement !== null);
  const beforeMove = await page.evaluate(() => window.lastBusDiagnostics().self);
  await page.keyboard.down('w'); await page.waitForTimeout(800); await page.keyboard.up('w');
  await page.waitForFunction(before => { const p = window.lastBusDiagnostics().self; return Math.hypot(p.x - before.x, p.z - before.z) > 0.4; }, beforeMove);
  await page.mouse.down(); await page.waitForTimeout(250); await page.mouse.up();
  await page.waitForFunction(() => Number(document.querySelector('#ammo').textContent) < 30);
  results.push('online movement and server-acknowledged ammunition');
  const diagnostics = await page.evaluate(() => window.lastBusDiagnostics());
  await page.evaluate(() => { location.hash = 'room=another-invitation'; });
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Leave your current game'));
  assert.equal(await page.locator('#join-modal').isVisible(), false);
  assert.equal(await page.evaluate(() => window.lastBusDiagnostics().connected), true);
  results.push('an invitation opened in the current tab works from the menu and preserves an active room');
  await page.evaluate(() => document.exitPointerLock()); await page.locator('#leave-game').click(); await page.locator('#confirm-yes').click();
  await friend.evaluate(() => document.exitPointerLock()); await friend.locator('#leave-game').click(); await friend.locator('#confirm-yes').click(); await second.close();
  assert.deepEqual(errors, []);
  await writeFile('artifacts/browser-report.json', JSON.stringify({ results, diagnostics, errors, note: 'Headless Chromium automation. Graphics backend is recorded separately in load-report.json; not a physical-display gaming benchmark.' }, null, 2));
  console.log(JSON.stringify({ results, diagnostics, errors }, null, 2));
} catch (error) { await page.screenshot({ path: 'artifacts/browser-failure.png' }); console.error(JSON.stringify({ error: error.message, errors, results })); process.exitCode = 1; }
finally { await browser.close(); }
